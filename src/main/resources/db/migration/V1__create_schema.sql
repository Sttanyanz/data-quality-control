-- 1. Создание ENUM-типов
CREATE TYPE goal_status AS ENUM ('ACTIVE', 'DONE', 'CANCELLED');
CREATE TYPE severity AS ENUM ('critical', 'major', 'minor');
CREATE TYPE issue_target AS ENUM ('GOAL', 'KR');
CREATE TYPE run_status AS ENUM ('RUNNING', 'COMPLETED', 'FAILED');

-- 2. Таблица подразделений (иерархия)
CREATE TABLE unit
(
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name      TEXT NOT NULL,
    parent_id BIGINT REFERENCES unit (id) ON DELETE RESTRICT,
    CHECK (id <> parent_id)
);
CREATE INDEX ix_unit_parent ON unit (parent_id);

-- 3. Таблица целей
CREATE TABLE goal
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title          TEXT        NOT NULL,
    unit_id        BIGINT      NOT NULL REFERENCES unit (id) ON DELETE RESTRICT,
    owner_id       BIGINT,
    parent_goal_id BIGINT      REFERENCES goal (id) ON DELETE SET NULL,
    status         goal_status NOT NULL,
    due_date       DATE
);
CREATE INDEX ix_goal_unit_status ON goal (unit_id, status);
CREATE INDEX ix_goal_parent ON goal (parent_goal_id);

-- 4. Таблица ключевых результатов (КР)
CREATE TABLE key_result
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            TEXT   NOT NULL,
    goal_id         BIGINT NOT NULL REFERENCES goal (id) ON DELETE CASCADE,
    target_value    NUMERIC(19, 4),
    actual_value    NUMERIC(19, 4),
    weight          NUMERIC(5, 2) CHECK (weight >= 0 AND weight <= 100),
    fact_updated_at TIMESTAMPTZ
);
CREATE INDEX ix_kr_goal ON key_result (goal_id);

-- 5. Справочник правил
CREATE TABLE kkd_rule
(
    id          SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        TEXT         NOT NULL UNIQUE,
    target_type issue_target NOT NULL,
    severity    severity     NOT NULL,
    title       TEXT         NOT NULL
);

-- 6. Таблица прогонов
CREATE TABLE kkd_run
(
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    snapshot_date      DATE       NOT NULL,
    compared_to_run_id BIGINT REFERENCES kkd_run (id) ON DELETE RESTRICT,
    status             run_status NOT NULL,
    CHECK (compared_to_run_id IS NULL OR compared_to_run_id <> id)
);
CREATE INDEX ix_run_status_date ON kkd_run (status, snapshot_date DESC);

-- 7. Таблица найденных проблем (Exclusive Arc)
CREATE TABLE kkd_issue
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id        BIGINT   NOT NULL REFERENCES kkd_run (id) ON DELETE CASCADE,
    rule_id       SMALLINT NOT NULL REFERENCES kkd_rule (id) ON DELETE RESTRICT,
    goal_id       BIGINT REFERENCES goal (id) ON DELETE RESTRICT,
    key_result_id BIGINT REFERENCES key_result (id) ON DELETE RESTRICT,
    severity      severity NOT NULL,
    message       TEXT     NOT NULL,
    CHECK (num_nonnulls(goal_id, key_result_id) = 1)
);

CREATE INDEX ix_issue_run ON kkd_issue (run_id);
CREATE INDEX ix_issue_run_severity ON kkd_issue (run_id, severity);
CREATE INDEX ix_issue_goal ON kkd_issue (goal_id) WHERE goal_id IS NOT NULL;
CREATE INDEX ix_issue_kr ON kkd_issue (key_result_id) WHERE key_result_id IS NOT NULL;
CREATE UNIQUE INDEX ux_issue_identity ON kkd_issue (run_id, rule_id, goal_id, key_result_id) NULLS NOT DISTINCT;